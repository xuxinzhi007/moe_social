#!/usr/bin/env bash
# FS-9b phase 1: pb/moe 为生成目标；pb/super 保留类型别名垫片（渐进改 import）。
set -euo pipefail
cd "$(dirname "$0")/.."

MOE_DIR="rpc/pb/moe"
SHIM="rpc/pb/super/shim_gen.go"

if [ ! -d "$MOE_DIR" ]; then
  echo "fs9b: skip shim ($MOE_DIR not found; run make gen-rpc after FS-9b go_package)"
  exit 0
fi

python3 - <<'PY'
from pathlib import Path
import re

root = Path("rpc/pb/moe")
types: list[str] = []
for p in sorted(root.glob("*.pb.go")):
    text = p.read_text(encoding="utf-8")
    for m in re.finditer(r"^type ([A-Z]\w+)", text, re.M):
        types.append(m.group(1))
types = sorted(set(types))
if not types:
    raise SystemExit("fs9b: no exported types in rpc/pb/moe")

out = Path("rpc/pb/super/shim_gen.go")
out.parent.mkdir(parents=True, exist_ok=True)
lines = [
    "// Code generated by scripts/fs9b-gen-pb-super-shim.sh; DO NOT EDIT.",
    "// FS-9b phase 1: import backend/rpc/pb/moe in new code; super package is deprecated.",
    "package super",
    "",
    "import (",
    "\tmoe \"backend/rpc/pb/moe\"",
    "",
    "\t\"google.golang.org/grpc\"",
    ")",
    "",
]
for t in types:
    lines.append(f"type {t} = moe.{t}")
lines.extend([
    "",
    "var NewSuperClient = moe.NewSuperClient",
    "",
    "func RegisterSuperServer(s grpc.ServiceRegistrar, srv SuperServer) {",
    "\tmoe.RegisterSuperServer(s, srv)",
    "}",
    "",
    "var Super_ServiceDesc = moe.Super_ServiceDesc",
    "",
])
out.write_text("\n".join(lines), encoding="utf-8")
print(f"fs9b: wrote {out} ({len(types)} type aliases + grpc shims)")
PY
