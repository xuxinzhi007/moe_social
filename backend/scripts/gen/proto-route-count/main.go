// 扫描 api/**/v1/*_http.pb.go 中的 r.METHOD 注册，生成 routestats/proto_routes_gen.go。
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

var routeRe = regexp.MustCompile(`r\.(GET|POST|PUT|DELETE|PATCH|HEAD|OPTIONS)\(`)

func main() {
	root := backendRoot()
	apiDir := filepath.Join(root, "api")
	count := 0
	err := filepath.WalkDir(apiDir, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() || !strings.HasSuffix(path, "_http.pb.go") {
			return nil
		}
		raw, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		count += len(routeRe.FindAllString(string(raw), -1))
		return nil
	})
	if err != nil {
		fmt.Fprintf(os.Stderr, "walk api: %v\n", err)
		os.Exit(1)
	}

	outPath := filepath.Join(root, "internal/server/routestats/proto_routes_gen.go")
	body := fmt.Sprintf(`// Code generated by scripts/gen/proto-route-count; DO NOT EDIT.

package routestats

const protoHTTPRouteCount = %d
`, count)
	if err := os.WriteFile(outPath, []byte(body), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "write: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("OK: proto HTTP routes=%d → %s\n", count, outPath)
}

func backendRoot() string {
	if root := strings.TrimSpace(os.Getenv("MOE_BACKEND_ROOT")); root != "" {
		return root
	}
	wd, _ := os.Getwd()
	for d := wd; d != filepath.Dir(d); d = filepath.Dir(d) {
		if _, err := os.Stat(filepath.Join(d, "go.mod")); err == nil {
			if _, err2 := os.Stat(filepath.Join(d, "Makefile")); err2 == nil {
				return d
			}
		}
	}
	return wd
}
